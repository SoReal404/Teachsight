import argparse, io, json
from pathlib import Path
import yaml, torch
from torchvision.models.detection import ssdlite320_mobilenet_v3_large
from PIL import Image
import torchvision.transforms.functional as TF

BASE_DIR = Path(__file__).resolve().parent


def load_model(weights_path=None, config_path=None, labels_path=None):
    weights_path = Path(weights_path) if weights_path else BASE_DIR / "best.pt"
    config_path = Path(config_path) if config_path else BASE_DIR / "config.yaml"
    labels_path = Path(labels_path) if labels_path else BASE_DIR / "labels.json"
    if not weights_path.exists():
        raise FileNotFoundError(f"Model weights not found at: {weights_path}")
    cfg = yaml.safe_load(config_path.read_text(encoding="utf-8"))
    labels = json.loads(labels_path.read_text(encoding="utf-8")) if labels_path.exists() else []
    device = torch.device("cuda" if torch.cuda.is_available() else "cpu")
    model = ssdlite320_mobilenet_v3_large(weights=None, num_classes=len(labels) + 1)
    model.load_state_dict(torch.load(weights_path, map_location=device))
    model.to(device).eval()
    return model, labels, device


def predict_image(image_input, score_threshold=0.35, top=20):
    """Find the objects in one picture. Returns a list of {label, confidence, box}."""
    model, labels, device = load_model()
    if isinstance(image_input, (str, Path)):
        img = Image.open(image_input).convert("RGB")
    elif isinstance(image_input, Image.Image):
        img = image_input.convert("RGB")
    else:
        img = Image.open(io.BytesIO(image_input)).convert("RGB")
    w, h = img.size
    tensor = TF.resize(TF.to_tensor(img), [320, 320])
    with torch.no_grad():
        out = model([tensor.to(device)])[0]
    found = []
    for box, score, label in zip(out["boxes"].cpu().tolist(), out["scores"].cpu().tolist(), out["labels"].cpu().tolist()):
        if score < score_threshold:
            continue
        idx = max(int(label) - 1, 0)
        found.append({
            "label": labels[idx] if idx < len(labels) else f"class_{label}",
            "confidence": round(float(score), 4),
            "box": [round(max(0, box[0]) / w, 4), round(max(0, box[1]) / h, 4),
                    round(min(w, box[2]) / w, 4), round(min(h, box[3]) / h, 4)],
        })
    found.sort(key=lambda d: -d["confidence"])
    return found[:top]


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description="Find objects in an image with your trained model.")
    parser.add_argument("image", help="Path to the image")
    parser.add_argument("--threshold", type=float, default=0.35, help="Lowest confidence to report")
