def write_run_files(run_dir: Path, cfg: dict, classes: list | None = None, metrics: dict | None = None):
    run_dir.mkdir(parents=True, exist_ok=True)
    (run_dir / "config.yaml").write_text(yaml.safe_dump(cfg, sort_keys=False), encoding="utf-8")
    detection_run = cfg.get("task") == "detection"
    if detection_run:
        (run_dir / "train.py").write_text(DETECT_TRAIN_PY, encoding="utf-8")
        (run_dir / "predict.py").write_text(DETECT_PREDICT_PY, encoding="utf-8")
        (run_dir / "serve.py").write_text(DETECT_SERVE_PY, encoding="utf-8")
        (run_dir / "detection_helpers.py").write_text(DETECTION_HELPERS_PY, encoding="utf-8")
    else:
        (run_dir / "train.py").write_text(TRAIN_PY, encoding="utf-8")
        (run_dir / "predict.py").write_text(PREDICT_PY, encoding="utf-8")
        (run_dir / "serve.py").write_text(SERVE_PY, encoding="utf-8")
    (run_dir / "requirements.txt").write_text(REQUIREMENTS_TXT, encoding="utf-8")
    if classes:
        (run_dir / "labels.json").write_text(json.dumps(classes, indent=2), encoding="utf-8")
    
    classes_list = classes or []
    if not classes_list and (run_dir / "labels.json").is_file():
        try:
            classes_list = json.loads((run_dir / "labels.json").read_text(encoding="utf-8"))
        except Exception:
            pass
    (run_dir / "README.md").write_text(generate_readme(cfg, classes_list, metrics), encoding="utf-8")


def ensure_export_bundle(run_dir: Path):
    """Ensures README.md, predict.py, serve.py, requirements.txt exist in any run directory."""
    if not run_dir.is_dir():
        return
    cfg_file = run_dir / "config.yaml"
    labels_file = run_dir / "labels.json"
    rep_file = run_dir / "report.json"
    
    cfg = yaml.safe_load(cfg_file.read_text(encoding="utf-8")) if cfg_file.is_file() else {"model": "resnet18", "image_size": 224}
    classes = json.loads(labels_file.read_text(encoding="utf-8")) if labels_file.is_file() else []
    metrics = None
    if rep_file.is_file():
        try:
            metrics = json.loads(rep_file.read_text(encoding="utf-8")).get("metrics")
        except Exception:
            pass

    detection_run = cfg.get("task") == "detection"
    if not (run_dir / "predict.py").is_file():
        (run_dir / "predict.py").write_text(DETECT_PREDICT_PY if detection_run else PREDICT_PY, encoding="utf-8")
    if not (run_dir / "serve.py").is_file():
        (run_dir / "serve.py").write_text(DETECT_SERVE_PY if detection_run else SERVE_PY, encoding="utf-8")
    if not (run_dir / "requirements.txt").is_file():
        (run_dir / "requirements.txt").write_text(REQUIREMENTS_TXT, encoding="utf-8")
    if not (run_dir / "train.py").is_file():
        (run_dir / "train.py").write_text(DETECT_TRAIN_PY if detection_run else TRAIN_PY, encoding="utf-8")
    if detection_run and not (run_dir / "detection_helpers.py").is_file():
        (run_dir / "detection_helpers.py").write_text(DETECTION_HELPERS_PY, encoding="utf-8")
    if not (run_dir / "README.md").is_file():
        (run_dir / "README.md").write_text(generate_readme(cfg, classes, metrics), encoding="utf-8")
